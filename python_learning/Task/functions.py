# Challenge 1: Define a function greet that takes a name as an argument and prints a greeting message.
def greet(name):
    """Prints a friendly greeting message to the provided name."""
    print(f"Hello, {name}! Welcome to the Python challenges.")

# Testing the greet function
greet("Alice")

# Challenge 2: Define a function calculate_area that takes length and width as arguments and returns the area of a rectangle.
def calculate_area(length, width):
    """Calculates and returns the area of a rectangle."""
    return length * width

# Testing the calculate_area function
area = calculate_area(5, 10)
print("Area of the rectangle:", area)
